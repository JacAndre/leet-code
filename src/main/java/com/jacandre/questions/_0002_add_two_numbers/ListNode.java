package com.jacandre.questions._0002_add_two_numbers;

public class ListNode {
    public int val;
    public ListNode next;

    ListNode () {
    }

    public ListNode(int val) {
        this.val = val;
    }

    public ListNode(int val, ListNode next) {
        this.val = val;
        this.next = next;
    }
}